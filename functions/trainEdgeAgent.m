function [agent, stats] = trainEdgeAgent(type, maxEpisodes, plots)
% Train an agent on the edge and save it to models/.
if nargin < 2, maxEpisodes = 1000; end
if nargin < 3, plots = "training-progress"; end
p = cubeParams();
r = rlParams();
env = createEdgeEnv(p, r);
agent = createAgent(type, env, p);

opt = rlTrainingOptions( ...
    MaxEpisodes = maxEpisodes, ...
    MaxStepsPerEpisode = r.maxSteps, ...
    ScoreAveragingWindowLength = 20, ...
    StopTrainingCriteria = "AverageReward", ...
    StopTrainingValue = 0.95*r.maxSteps, ...
    Plots = plots, ...
    Verbose = plots == "none");
stats = train(agent, env, opt);

root = fileparts(fileparts(mfilename("fullpath")));
save(fullfile(root, "models", "edge" + upper(type) + ".mat"), "agent", "stats", "p", "r");
end
